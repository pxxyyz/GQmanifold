function result = native_design_diagnostics(s)
% NATIVE_DESIGN_DIAGNOSTICS  Residuals of the native design LP and QP.
%
% function result = native_design_diagnostics(state)
%
% Recomputes the mode spread, primal violations, stationarity residuals,
% duality gaps, dual negativity, and complementarity residuals from the
% sparse state returned by native_design_fast.m. Called after the setup
% timers stop; it does no optimization.
mode=s.a+s.F*s.z2(1:size(s.F,2));
result=struct('mode_spread',max(mode)-min(mode),'spread_bound',s.b2(end),...
 'lp_primal_violation',max([0;s.A*s.z1-s.b;abs(s.E*s.z1-s.be)]),...
 'qp_primal_violation',max([0;s.A2*s.z2-s.b2;abs(s.E*s.z2-s.be)]),...
 'lp_stationarity_inf',norm(s.f+s.A'*s.lambda1.ineqlin+s.E'*s.lambda1.eqlin(:),inf),...
 'qp_stationarity_inf',norm(s.H*s.z2+s.A2'*s.lambda2.ineqlin+s.E'*s.lambda2.eqlin(:),inf),...
 'lp_gap',s.f'*s.z1+s.b'*s.lambda1.ineqlin+sum(s.be.*s.lambda1.eqlin(:)),...
 'qp_kkt_gap',s.z2'*s.H*s.z2+s.b2'*s.lambda2.ineqlin+sum(s.be.*s.lambda2.eqlin(:)),...
 'lp_dual_negativity',max([0;-s.lambda1.ineqlin]),'qp_dual_negativity',max([0;-s.lambda2.ineqlin]),...
 'lp_complementarity_inf',norm(s.lambda1.ineqlin.*(s.A*s.z1-s.b),inf),...
 'qp_complementarity_inf',norm(s.lambda2.ineqlin.*(s.A2*s.z2-s.b2),inf));
end
